/** 小文字の ASCII 英字は大文字のグリフで描く。 */
private fun glyphKey(char: Char): Char = if (char in 'a'..'z') char.uppercaseChar() else char

fun hasDotMatrixGlyph(char: Char): Boolean = glyphKey(char) in GLYPHS

fun dotMatrixGlyph(char: Char): List<String> = GLYPHS[glyphKey(char)] ?: BLANK_GLYPH
